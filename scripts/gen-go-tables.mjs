// Generate Go data tables from the built TypeScript library.
//
// The Go port must preserve exact part ids, ordering, vibe tags, glyphs,
// presets, states and automatic-name ordering. Those are persistence
// contracts, so the tables are generated from the source of truth rather than
// hand-copied.
//
// Run after `npm run build`:
//   node scripts/gen-go-tables.mjs
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lib = await import(resolve(root, "dist/index.js"));
const { BODIES, EYES, MOUTHS, FACE_PRESETS, STATES } = lib;

if (BODIES.length !== 27 || EYES.length !== 16 || MOUTHS.length !== 15) {
  throw new Error(`unexpected table sizes: ${BODIES.length}/${EYES.length}/${MOUTHS.length}`);
}

const namesSource = await readFile(resolve(root, "src/names.ts"), "utf8");
const namesBlock = namesSource.match(/const FIRST_NAMES = \[([\s\S]*?)\] as const;/);
if (!namesBlock) throw new Error("FIRST_NAMES block not found");
const FIRST_NAMES = [...namesBlock[1].matchAll(/"([^"]*)"/g)].map((m) => m[1]);
if (FIRST_NAMES.length !== 324) throw new Error(`unexpected name count: ${FIRST_NAMES.length}`);

function goQuote(value) {
  let out = '"';
  for (const ch of value) {
    const cp = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === "\\") out += "\\\\";
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (cp < 0x20) out += `\\u${cp.toString(16).padStart(4, "0")}`;
    else out += ch;
  }
  return out + '"';
}

const camel = (id) => id.replace(/(^|[-_])([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const lines = [];
lines.push("// Code generated by scripts/gen-go-tables.mjs; DO NOT EDIT.");
lines.push("// Source: src/parts.ts, src/states.ts, src/presets.ts, src/names.ts.");
lines.push("package faceroll");
lines.push("");

lines.push("// Body ids. Values are a persistence contract: never rename or reorder.");
for (const body of BODIES) lines.push(`const Body${camel(body.id)} BodyID = ${goQuote(body.id)}`);
lines.push("");
lines.push("// Eyes ids. Values are a persistence contract: never rename or reorder.");
for (const eyes of EYES) lines.push(`const Eyes${camel(eyes.id)} EyesID = ${goQuote(eyes.id)}`);
lines.push("");
lines.push("// Mouth ids. Values are a persistence contract: never rename or reorder.");
for (const mouth of MOUTHS) lines.push(`const Mouth${camel(mouth.id)} MouthID = ${goQuote(mouth.id)}`);
lines.push("");
lines.push("// State ids. Values are a persistence contract: never rename or reorder.");
for (const state of STATES) lines.push(`const State${camel(state.id)} StateName = ${goQuote(state.id)}`);
lines.push("");

lines.push("var Bodies = []BodyDef{");
for (const body of BODIES) {
  lines.push(
    `\t{ID: Body${camel(body.id)}, Left: ${goQuote(body.left)}, Right: ${goQuote(body.right)}, ` +
      `Vibes: ${goVibes(body.vibes)}, Mouth: ${body.mouth ? `Mouth${camel(body.mouth)}` : '""'}},`,
  );
}
lines.push("}");
lines.push("");

lines.push("var Eyes = []EyeDef{");
for (const eyes of EYES) {
  const expr = (name) => `Pair{Left: ${goQuote(eyes[name][0])}, Right: ${goQuote(eyes[name][1])}}`;
  lines.push(
    `\t{ID: Eyes${camel(eyes.id)}, Vibes: ${goVibes(eyes.vibes)}, Open: ${expr("open")}, ` +
      `Blink: ${expr("blink")}, Happy: ${expr("happy")}, Wide: ${expr("wide")}, ` +
      `Sad: ${expr("sad")}, Angry: ${expr("angry")}, Sleep: ${expr("sleep")}},`,
  );
}
lines.push("}");
lines.push("");

lines.push("var Mouths = []MouthDef{");
for (const mouth of MOUTHS) {
  lines.push(
    `\t{ID: Mouth${camel(mouth.id)}, Vibes: ${goVibes(mouth.vibes)}, Calm: ${goQuote(mouth.calm)}, ` +
      `Smile: ${goQuote(mouth.smile)}, Big: ${goQuote(mouth.big)}, Open: ${goQuote(mouth.open)}, ` +
      `Sad: ${goQuote(mouth.sad)}, Flat: ${goQuote(mouth.flat)}, Unsure: ${goQuote(mouth.unsure)}, ` +
      `Angry: ${goQuote(mouth.angry)}, Sleep: ${goQuote(mouth.sleep)}},`,
  );
}
lines.push("}");
lines.push("");

lines.push("var States = []StateInfo{");
for (const state of STATES) {
  lines.push(
    `\t{ID: State${camel(state.id)}, Label: ${goQuote(state.label)}, Kind: ${goQuote(state.kind)}, ` +
      `Use: ${goQuote(state.use)}, Say: ${goQuote(state.say)}},`,
  );
}
lines.push("}");
lines.push("");

lines.push("// FacePresets is the 24 named starting faces, in display order.");
lines.push("var FacePresets = []FacePreset{");
for (const preset of FACE_PRESETS) {
  lines.push(
    `\t{ID: Preset${camel(preset.id)}, Label: ${goQuote(preset.label)}, Vibe: ${goQuote(preset.vibe)}, ` +
      `Parts: Parts{Body: Body${camel(preset.parts.body)}, Eyes: Eyes${camel(preset.parts.eyes)}, ` +
      `Mouth: Mouth${camel(preset.parts.mouth)}}},`,
  );
}
lines.push("}");
lines.push("");
for (const preset of FACE_PRESETS) lines.push(`const Preset${camel(preset.id)} PresetID = ${goQuote(preset.id)}`);
lines.push("");

lines.push("// firstNameTable is the stable automatic-name pool. Never reorder.");
lines.push("var firstNameTable = []string{");
for (let i = 0; i < FIRST_NAMES.length; i += 6) {
  lines.push(`\t${FIRST_NAMES.slice(i, i + 6).map(goQuote).join(", ")},`);
}
lines.push("}");
lines.push("");

await mkdir(resolve(root, "go"), { recursive: true });
await writeFile(resolve(root, "go/tables_gen.go"), lines.join("\n"));

function goVibes(vibes) {
  return `[]VibeTag{${vibes.map((v) => `VibeTag("${v}")`).join(", ")}}`;
}

console.log(`wrote go/tables_gen.go (${BODIES.length} bodies, ${EYES.length} eyes, ${MOUTHS.length} mouths, ${FACE_PRESETS.length} presets, ${FIRST_NAMES.length} names)`);
