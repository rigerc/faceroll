// Generate cross-language parity fixtures for the Go port.
//
// Run after `npm run build`:
//   node scripts/gen-go-fixtures.mjs
//   node scripts/gen-go-fixtures.mjs --check   # fail if fixtures are stale
//
// The fixtures pin the TypeScript implementation's output for seeded RNG,
// automatic names, all 6480 characters, presets, children and exporters.
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lib = await import(resolve(root, "dist/index.js"));
const {
  BODIES,
  EYES,
  MOUTHS,
  STATES,
  FACE_PRESETS,
  createCharacter,
  createPresetCharacter,
  rollCharacter,
  rerollPart,
  deriveChildCharacters,
  childCapacity,
  serialize,
  toSystemPrompt,
  toMarkdown,
  toNodeSource,
  hashSeed,
  seededRng,
  nameForParts,
} = lib;

const SEP = "\u001f";

function fingerprint(character) {
  const chunks = [
    character.name,
    character.nameMode ?? "",
    character.seed ?? "",
    character.parts.body,
    character.parts.eyes,
    character.parts.mouth,
  ];
  for (const state of STATES) {
    const animation = character.animations[state.id];
    chunks.push(state.id, animation.still, String(animation.frames.length));
    for (const frame of animation.frames) chunks.push(String(frame.ms), frame.text);
  }
  return createHash("sha256").update(chunks.join(SEP), "utf8").digest("hex");
}

function childFingerprint(children) {
  return createHash("sha256").update(children.map(fingerprint).join(SEP), "utf8").digest("hex");
}

const fixtures = {
  source: {
    package: "faceroll",
    // Parity target, not the current npm version. Only change this when the Go
    // port intentionally re-baselines against a different TypeScript release.
    version: "1.0.0",
    note: "Generated by scripts/gen-go-fixtures.mjs. Do not edit.",
  },
  rng: (() => {
    const seeds = [
      "pixel",
      "",
      "0",
      "123",
      "café",
      "ʕ•ᴥ•ʔ",
      "🎲",
      'a"b\\c',
      "\u2028",
      "a".repeat(1000),
    ];
    return seeds.map((seed) => {
      const rng = seededRng(seed);
      return {
        seed,
        hash: hashSeed(seed),
        values: Array.from({ length: 24 }, () => rng()),
      };
    });
  })(),
  rolls: (() => {
    const cases = [
      { seed: "pixel" },
      { seed: "8", vibe: "cute" },
      { seed: "weird", vibe: "weird" },
      { seed: "lock", lock: { body: "wave", eyes: "ring" } },
      { seed: "all", lock: { body: "bear", eyes: "cat", mouth: "w" } },
      { seed: "ʕ•ᴥ•ʔ", vibe: "cool" },
      { seed: "🎲" },
      { seed: 'a"b\\c' },
      { seed: "7", name: "Pixel" },
    ];
    return cases.map((entry) => {
      const character = lib.rollCharacter(entry);
      return {
        ...entry,
        expected: {
          parts: character.parts,
          name: character.name,
          nameMode: character.nameMode,
          seed: character.seed,
        },
      };
    });
  })(),
  rerolls: (() => {
    const base = createCharacter({ body: "round", eyes: "dot", mouth: "w" });
    const cases = [];
    for (const kind of ["body", "eyes", "mouth"]) {
      for (const seed of ["reroll-1", "reroll-2", "ʕ•ʔ"]) {
        const character = lib.rerollPart(base, kind, { seed });
        cases.push({
          base: base.parts,
          kind,
          seed,
          expected: { parts: character.parts, name: character.name, nameMode: character.nameMode, seed: character.seed },
        });
      }
    }
    return cases;
  })(),
  names: (() => {
    const names = [];
    for (const body of BODIES) {
      for (const eyes of EYES) {
        for (const mouth of MOUTHS) {
          names.push(nameForParts({ body: body.id, eyes: eyes.id, mouth: mouth.id }));
        }
      }
    }
    return names;
  })(),
  characters: (() => {
    const fingerprints = [];
    for (const body of BODIES) {
      for (const eyes of EYES) {
        for (const mouth of MOUTHS) {
          fingerprints.push(fingerprint(createCharacter({ body: body.id, eyes: eyes.id, mouth: mouth.id })));
        }
      }
    }
    return fingerprints;
  })(),
  presets: FACE_PRESETS.map((preset) => ({
    id: preset.id,
    character: createPresetCharacter(preset.id),
    json: JSON.stringify(serialize(createPresetCharacter(preset.id)), null, 2),
  })),
  exports: [
    { label: "preset-kitty", create: { preset: "kitty" } },
    { label: "seed-pixel", create: { seed: "pixel", parts: null } },
    {
      label: "custom-name-html",
      create: { seed: "abc", name: "<Pixel & Co>", parts: { body: "round", eyes: "dot", mouth: "w" } },
    },
    { label: "bear", create: { seed: "abc", name: "Pixel", parts: { body: "bear", eyes: "dot", mouth: "w" } } },
    {
      label: "unicode-seed",
      create: { seed: "ʕ•ᴥ•ʔ", parts: { body: "cloud", eyes: "sparkle", mouth: "heart" } },
    },
  ].map((entry) => {
    const character = entry.create.preset
      ? createPresetCharacter(entry.create.preset)
      : createCharacter(
          entry.create.parts ?? lib.rollCharacter({ seed: entry.create.seed }).parts,
          {
            ...(entry.create.name !== undefined ? { name: entry.create.name } : {}),
            ...(entry.create.seed !== undefined ? { seed: entry.create.seed } : {}),
          },
        );
    return {
      label: entry.label,
      parts: character.parts,
      ...(character.nameMode === "custom" ? { customName: character.name } : {}),
      ...(character.seed !== undefined ? { seed: character.seed } : {}),
      name: character.name,
      fingerprint: fingerprint(character),
      prompt: toSystemPrompt(character),
      markdown: toMarkdown(character),
      json: JSON.stringify(serialize(character), null, 2),
      node: toNodeSource(character),
    };
  }),
  children: (() => {
    const combos = [
      { eyes: "dot", mouth: "w" },
      { eyes: "ring", mouth: "fang" },
    ];
    const seeds = [null, "family", "ʕ•ᴥ•ʔ", 'a"b\\c', "\u2028"];
    const out = [];
    for (const body of BODIES) {
      for (const combo of combos) {
        const parts = { body: body.id, eyes: combo.eyes, mouth: combo.mouth };
        const parent = createCharacter(parts);
        const capacity = childCapacity(parent);
        out.push({
          parts,
          capacity,
          seeds: seeds.map((seed) => {
            const children = deriveChildCharacters(parent, {
              count: capacity,
              ...(seed !== null ? { seed } : {}),
            });
            return {
              seed,
              fingerprint: childFingerprint(children),
              first: children.slice(0, 3).map((child) => ({
                still: child.animations.idle.still,
                name: child.name,
                parts: child.parts,
              })),
            };
          }),
        });
      }
    }
    return out;
  })(),
};

const output = JSON.stringify(fixtures, null, 2) + "\n";
const target = resolve(root, "go/testdata/parity.json");
await mkdir(dirname(target), { recursive: true });

if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8").catch(() => "");
  if (existing !== output) {
    console.error("go/testdata/parity.json is stale; run node scripts/gen-go-fixtures.mjs");
    process.exit(1);
  }
  console.log("go/testdata/parity.json is up to date");
} else {
  await writeFile(target, output);
  console.log(
    `wrote go/testdata/parity.json (${fixtures.names.length} names, ${fixtures.characters.length} characters, ` +
      `${fixtures.presets.length} presets, ${fixtures.children.length} families)`,
  );
}
